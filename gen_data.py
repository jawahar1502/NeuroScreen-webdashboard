"""Generate SYNTHETIC resting-state EEG for demo/testing only (not real patient data).

MDD-like recordings get literature-inspired but deliberately noisy differences:
right>left frontal alpha, higher frontal theta, slightly lower beta. Effects vary per
subject so the classifier does not reach a perfect score.
"""
import numpy as np, csv, os
from common import FS, CHANNELS

from pathlib import Path
OUT = os.environ.get("OUT", str(Path(__file__).resolve().parent / "dataset"))
rng = np.random.default_rng(int(os.environ.get("SEED", 42)))
N_SUBJECTS, DUR = int(os.environ.get("N", 40)), int(os.environ.get("DUR", 45))  # DUR=90 for longer recordings
os.makedirs(OUT, exist_ok=True)
t = np.arange(DUR * FS) / FS
ix = {c: i for i, c in enumerate(CHANNELS)}


def pink(n):
    f = np.fft.rfftfreq(n, 1 / FS); f[0] = f[1]
    s = np.fft.irfft((rng.normal(size=f.size) + 1j * rng.normal(size=f.size)) / np.sqrt(f), n)
    return s / s.std()


rows = []
for s in range(N_SUBJECTS):
    label = int(s % 2 == 0)  # 1 = MDD, 0 = healthy
    strength = rng.uniform(0.0, 1.0) * label       # per-subject effect size
    alpha_f = rng.uniform(9, 11)
    x = np.zeros((len(CHANNELS), t.size))
    for c, name in enumerate(CHANNELS):
        occ = 1.6 if name in ("O1", "O2", "Pz", "P3", "P4") else 1.0
        alpha_amp = 4.0 * occ * rng.uniform(0.8, 1.2)
        theta_amp = 2.0 + 1.6 * strength * (name.startswith("F") or name == "Fz")
        beta_amp = 1.2 * (1 - 0.25 * strength)
        if name in ("F4", "F8"):
            alpha_amp *= 1 + 0.5 * strength           # right frontal alpha up
        if name in ("F3", "F7"):
            alpha_amp *= 1 - 0.25 * strength          # left frontal alpha down
        x[c] = (8 * pink(t.size)
                + alpha_amp * np.sin(2 * np.pi * alpha_f * t + rng.uniform(0, 6.28))
                + theta_amp * np.sin(2 * np.pi * rng.uniform(5, 7) * t + rng.uniform(0, 6.28))
                + beta_amp * np.sin(2 * np.pi * rng.uniform(18, 24) * t + rng.uniform(0, 6.28))
                + 1.0 * rng.normal(size=t.size))
    x += 0.8 * np.sin(2 * np.pi * 50 * t)               # mains noise
    name = f"subject_{s:03d}"
    np.save(f"{OUT}/{name}.npy", x.astype(np.float16))  # float16 keeps the files small; plenty of precision for EEG
    rows.append((f"{name}.npy", name, label))

with open(f"{OUT}/labels.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["file", "subject", "label"]); w.writerows(rows)
open(f"{OUT}/SYNTHETIC", "w").write("generated by gen_data.py")
print(f"wrote {len(rows)} recordings to {OUT}/")
